import type { MatchingQuestion, McqQuestion, WrittenQuestion } from '../types'

const mcq = (
  id: string,
  prompt: string,
  options: string[],
  correctIndex: number,
  explanation: string,
): McqQuestion => ({
  id,
  type: 'mcq',
  prompt,
  marks: 1,
  options,
  correctIndex,
  explanation,
  modelAnswer: options[correctIndex],
})

const essay = (
  id: string,
  prompt: string,
  modelAnswer: string,
  points: { point: string; keywords: string[] }[],
  explanation: string,
): WrittenQuestion => ({
  id,
  type: 'essay',
  prompt,
  marks: 4,
  explanation,
  modelAnswer,
  markingGuide: points.map((point) => ({ ...point, marks: 1 })),
})

const sql = (
  id: string,
  prompt: string,
  solution: string,
  points: { point: string; keywords: string[] }[],
  explanation: string,
): WrittenQuestion => ({
  id,
  type: 'sql',
  prompt,
  marks: 5,
  explanation,
  modelAnswer: solution,
  sqlSolution: solution,
  markingGuide: points.map((point) => ({ ...point, marks: 1 })),
})

