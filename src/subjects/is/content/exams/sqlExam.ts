const mcq = (
  id: string,
  prompt: string,
  options: string[],
  correctIndex: number,
  explanation: string,
): McqQuestion => ({
  id,
  type: 'mcq',
  prompt,
  marks: 1,
  options,
  correctIndex,
  explanation,
  modelAnswer: options[correctIndex],
})

const tf = (
  id: string,
  prompt: string,
  correct: boolean,
  explanation: string,
): TrueFalseQuestion => ({
  id,
  type: 'truefalse',
  prompt,
  marks: 1,
  correct,
  explanation,
  modelAnswer: correct ? 'True' : 'False',
})

const short = (
  id: string,
  prompt: string,
  modelAnswer: string,
  points: { point: string; keywords: string[] }[],
  explanation: string,
  commonMistakes?: string,
): WrittenQuestion => ({
  id,
  type: 'short',
  prompt,
  marks: 3,
  explanation,
  modelAnswer,
  commonMistakes,
  markingGuide: points.map((point) => ({ ...point, marks: 1 })),
})

const sql = (
  id: string,
  prompt: string,
  solution: string,
  points: { point: string; keywords: string[] }[],
  explanation: string,
  commonMistakes?: string,
): WrittenQuestion => ({
  id,
  type: 'sql',
  prompt,
  marks: 5,
  explanation,
  modelAnswer: solution,
  sqlSolution: solution,
  commonMistakes,
  markingGuide: points.map((point) => ({ ...point, marks: 1 })),
})

